namespace $ {

	/**
	 * Адреса соседних узлов задаются переменной окружения GIPER_BAZA_MASTERS
	 * через запятую.
	 *
	 * В браузере список мастеров наполняется сам — туда попадает origin, с
	 * которого отдана страница. На сервере origin взять неоткуда, а Seed для
	 * холодного старта не годится: список пиров читается через синхронизацию,
	 * которую не с кем провести, пока мастер неизвестен. Поэтому узлу нужен
	 * способ узнать соседей до первого соединения.
	 */
	const masters = process.env.GIPER_BAZA_MASTERS

	if( masters ) {
		$giper_baza_yard.masters_default.push(
			... masters.split( ',' ).map( url => url.trim() ).filter( Boolean )
		)
	}

}
